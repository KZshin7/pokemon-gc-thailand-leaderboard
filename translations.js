export function applyTranslations(language, root = document) {
  const selectedLanguage = normalizeLanguage(language);
  root.documentElement.lang = selectedLanguage;
  root.title = translate(selectedLanguage, "pageTitle");

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(selectedLanguage, element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(selectedLanguage, element.dataset.i18nAriaLabel));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(selectedLanguage, element.dataset.i18nPlaceholder));
  });
}
