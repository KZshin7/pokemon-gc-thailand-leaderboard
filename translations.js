export function normalizeLanguage(language) {
  return language === "th" ? "th" : "en";
}

export function loadLanguagePreference(storage) {
  return normalizeLanguage(storage.getItem(LANGUAGE_STORAGE_KEY));
}

export function saveLanguagePreference(language, storage) {
  storage.setItem(LANGUAGE_STORAGE_KEY, normalizeLanguage(language));
}

export function translate(language, key, values = {}) {
  const selectedLanguage = normalizeLanguage(language);
  const template = translations[selectedLanguage][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

